import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { load } from 'cheerio';
import sharp from 'sharp';
import prettier from 'prettier';
import { specialistPrograms } from '../../src/data/programs.ts';
import { seededTraining } from '../../src/data/program-labs.ts';
await mkdir('public/illustrations/program-guides', { recursive: true });
for (const [kind, name] of [
  ['robotics', 'navigation-grid'],
  ['research', 'seeded-qlearning'],
  ['hardware', 'roofline-example'],
]) {
  const program = specialistPrograms.find((p) => p.icon === kind);
  const $ = load(
    await readFile('dist/programs/' + program.id + '/index.html', 'utf8'),
  );
  const svg = $('[data-lab] .map-svg').first();
  svg.attr('xmlns', 'http://www.w3.org/2000/svg');
  svg.attr('color', '#152747');
  svg.attr('font-family', 'Arial, sans-serif');
  const description = $('<desc></desc>').text(
    $('[data-lab] .chart-note').first().text().trim(),
  );
  svg.prepend(description);
  svg.find('text').attr('font-size', '16');
  const source = $.html(svg) + '\n';
  await sharp(Buffer.from(source)).metadata();
  await writeFile(
    'public/illustrations/program-guides/' + name + '.svg',
    source,
  );
}
await writeFile(
  'public/examples/programs/q-learning-seed17.json',
  await prettier.format(
    JSON.stringify(
      {
        environment:
          '4x4 grid; start(0,0); goal(3,3); obstacles(1,1),(2,1),(1,3)',
        algorithm: 'tabular Q-learning',
        seed: 17,
        episodes: 80,
        stepCap: 40,
        alpha: 0.5,
        gamma: 0.9,
        epsilon: 0.25,
        reward:
          '-1/move; -4 extra collision; +20 extra goal; terminal has no bootstrap',
        provenance:
          'Generated by src/data/program-labs.ts; reproduced by the Python exercise',
        returns: seededTraining().returns,
      },
      null,
      2,
    ),
    { parser: 'json' },
  ),
);
